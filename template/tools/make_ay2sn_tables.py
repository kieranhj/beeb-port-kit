"""Generate src/lib/ay2sn_tables.6502 - ay2sn's lookup tables for the CPC's 1 MHz AY.

Forked from Unspoken's tools/make_ay2sn_tables.py (itself from arkos-player-bbc's
tools/make_tables.py, which assumed the CPC). On the CPC the AY clock is 1,000,000 Hz, so the
SN period is exactly twice the AY period (SN f = 4e6 / (32 N), AY f = 1e6 / (16 P)): a shift, no
tone tables. Isometrikum never uses the envelope (R11-R13 never written, R8-R10 bit 4 never set:
the player writes volume >> 4), so the envelope tables are gone with the generator.

  ym_sn_vol       5-bit AY level -> SN attenuation (unchanged)
  ay_noise_rate   nearest SN white-noise rate by frequency, at 1 MHz

Usage: python tools/make_ay2sn_tables.py [--check]
"""
import os
import sys

AY_CLOCK = 1000000
SN_CLOCK = 4000000
_HERE = os.path.dirname(os.path.abspath(__file__))
# A project's src/lib/ (where the fork lives); in the kit itself, lib/ beside template/.
OUT = os.path.join(_HERE, '..', 'src', 'lib', 'ay2sn_tables.6502')
if not os.path.exists(OUT):
    OUT = os.path.join(_HERE, '..', '..', 'lib', 'ay2sn_tables.6502')


def rows(name, vals, per=16):
    out = ['.%s' % name]
    for i in range(0, len(vals), per):
        out.append('    EQUB ' + ', '.join('&%02X' % v for v in vals[i:i + per]))
    return out


def ym_sn_vol():
    return [15 - ((min(n + 1, 31) >> 1) & 15) for n in range(32)]


def ay_noise_rate():
    sn = [SN_CLOCK / (32.0 * 16 * (1 << r)) for r in range(3)]
    return [min(range(3), key=lambda r: abs(AY_CLOCK / (16.0 * max(n, 1)) - sn[r]))
            for n in range(32)]


def text():
    lines = ['\\ Generated by tools/make_ay2sn_tables.py - do not edit. AY clock %d Hz; SN N = 2 x AY P.' % AY_CLOCK]
    lines += rows('ym_sn_vol', ym_sn_vol())
    lines += rows('ay_noise_rate', ay_noise_rate())
    return '\n'.join(lines) + '\n'


def main():
    t = text()
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == t
        print('ay2sn_tables.6502', 'matches' if same else '*** DIFFERS ***')
        return 0 if same else 1
    with open(OUT, 'w', newline='\n') as f:
        f.write(t)
    print('wrote', os.path.normpath(OUT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
